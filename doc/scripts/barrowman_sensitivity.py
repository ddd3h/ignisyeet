#!/usr/bin/env python3
"""Sensitivity of the Barrowman inputs: one `ignisyeet sim` per row, written to
doc/data/sensitivity/barrowman_keys.csv.  Usage:
  barrowman_sensitivity.py <repo-root> <scratch-dir>
Each case is: ignisyeet sim examples/sample.toml --set resources.threads=4 --set KEY=VALUE ... --out <scratch>/<case>
(aero.method = barrowman, wind 4 m/s from north, parachute descent, rk4, as in the sample file)."""
import csv, json, subprocess, sys, pathlib

root = pathlib.Path(sys.argv[1]); scratch = pathlib.Path(sys.argv[2])
exe = root / "target/release/ignisyeet"
ov = {"count": 4, "root_chord": 0.20, "tip_chord": 0.10, "span": 0.10, "sweep": 0.08,
      "thickness": 0.004, "x_le_root": 1.30}
def fo(**kw):
    d = dict(ov); d.update(kw)
    return [f"rocket.fin_override.{k}={v}" for k, v in d.items()]
cases = [
    ("base", "baseline", []),
    ("fin_le_sharp", 'rocket.fin_le = "sharp"', ["rocket.fin_le=sharp"]),
    ("fin_te_tapered", 'rocket.fin_te = "tapered"', ["rocket.fin_te=tapered"]),
    ("rough_20", "rocket.roughness = 20e-6", ["rocket.roughness=20e-6"]),
    ("rough_120", "rocket.roughness = 120e-6", ["rocket.roughness=120e-6"]),
    ("cd_0", "rocket.extra_cd = 0", ["rocket.extra_cd=0"]),
    ("cd_04", "rocket.extra_cd = 0.04", ["rocket.extra_cd=0.04"]),
    ("cant_05", "rocket.fin_cant_deg = 0.5", ["rocket.fin_cant_deg=0.5"]),
    ("cant_10", "rocket.fin_cant_deg = 1.0", ["rocket.fin_cant_deg=1.0"]),
    ("ovr_same", "rocket.fin_override = detected values (rounded)", fo()),
    ("ovr_span_110", "fin_override.span = 0.11 (+10 %)", fo(span=0.11)),
    ("ovr_span_090", "fin_override.span = 0.09 (-10 %)", fo(span=0.09)),
    ("ovr_count_3", "fin_override.count = 3", fo(count=3)),
    ("ovr_xle_m20", "fin_override.x_le_root = 1.28 (-20 mm)", fo(x_le_root=1.28)),
]
def at_mach(path, m):
    best = None
    for r in csv.DictReader(open(path)):
        if float(r["alpha_deg"]) != 0: continue
        if best is None or abs(float(r["mach"]) - m) < abs(float(best["mach"]) - m): best = r
    return best
cols = ["case", "change", "apogee_m", "landing_distance_m", "min_stability_cal",
        "ca_off_M0.3", "cna_M0.3", "xcp_M0.3_m", "cl_delta_M0.3", "ca_off_M2.0", "cna_M2.0", "xcp_M2.0_m"]
rows = []
for name, label, sets in cases:
    out = scratch / name
    cmd = [str(exe), "sim", str(root / "examples/sample.toml"), "--set", "resources.threads=4"]
    for s in sets: cmd += ["--set", s]
    cmd += ["--out", str(out)]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    s = json.load(open(out / "summary.json"))
    a, b = at_mach(out / "aero_table.csv", 0.3), at_mach(out / "aero_table.csv", 2.0)
    rows.append([name, label, f"{s['apogee']:.1f}", f"{s['landing_distance']:.1f}", f"{s['min_stability_cal']:.3f}",
                 f"{float(a['ca_off']):.4f}", f"{float(a['cna']):.3f}", f"{float(a['xcp']):.4f}", f"{float(a['cl_delta']):.3f}",
                 f"{float(b['ca_off']):.4f}", f"{float(b['cna']):.3f}", f"{float(b['xcp']):.4f}"])
    print(rows[-1], flush=True)
dest = root / "doc/data/sensitivity/barrowman_keys.csv"
dest.parent.mkdir(parents=True, exist_ok=True)
with open(dest, "w", newline="") as f:
    f.write("# ignisyeet sim examples/sample.toml --set resources.threads=4 [--set KEY=VALUE ...] --out DIR  (aero.method=barrowman, wind 4 m/s from north, parachute, rk4)\n")
    f.write("# fin_override rows set count=4 root_chord=0.20 tip_chord=0.10 span=0.10 sweep=0.08 thickness=0.004 x_le_root=1.30 plus the change shown\n")
    f.write("# generated by doc/scripts/barrowman_sensitivity.py; aero columns are the alpha=0 rows of aero_table.csv nearest to the stated Mach number\n")
    w = csv.writer(f); w.writerow(cols); w.writerows(rows)
